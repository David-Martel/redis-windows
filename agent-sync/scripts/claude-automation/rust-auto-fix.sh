#!/bin/bash
# Rust Auto-Fix Script for agent-sync project
# Integrates with Claude framework automation tools

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
CLAUDE_ROOT="${CLAUDE_ROOT:-$HOME/.claude}"

echo "🦀 Rust Auto-Fix Script for agent-sync"
echo "Project root: $PROJECT_ROOT"
echo "Claude root: $CLAUDE_ROOT"

# Check if we're in a Rust project
if [ ! -f "$PROJECT_ROOT/Cargo.toml" ]; then
    echo "❌ No Cargo.toml found. Not a Rust project?"
    exit 1
fi

# Phase 1: Environment validation
echo "📋 Phase 1: Environment validation..."
cd "$PROJECT_ROOT"

# Check for required tools
check_tool() {
    if command -v "$1" &> /dev/null; then
        echo "✅ $1 found: $(command -v "$1")"
    else
        echo "❌ $1 not found"
        return 1
    fi
}

echo "Checking required tools..."
check_tool cargo
check_tool rustc

# Check for AST-grep
if command -v sg &> /dev/null; then
    echo "✅ ast-grep found: $(sg --version)"
    AST_GREP_CMD="sg"
elif [ -f "$CLAUDE_ROOT/ast-grep.exe" ]; then
    echo "✅ ast-grep found: $CLAUDE_ROOT/ast-grep.exe"
    AST_GREP_CMD="$CLAUDE_ROOT/ast-grep.exe"
else
    echo "⚠️ ast-grep not found, will install"
    cargo install ast-grep --locked
    AST_GREP_CMD="sg"
fi

# Phase 2: Pre-flight checks
echo "📋 Phase 2: Pre-flight checks..."

# Backup current state
echo "Creating backup..."
git stash push -m "rust-auto-fix-backup-$(date +%Y%m%d-%H%M%S)" --include-untracked || echo "No changes to stash"

# Check compilation before fixes
echo "Checking compilation before fixes..."
if cargo check --all-targets --all-features; then
    echo "✅ Project compiles successfully"
else
    echo "⚠️ Project has compilation issues"
fi

# Phase 3: AST-grep fixes
echo "🔍 Phase 3: AST-grep structural fixes..."

if [ -f "sgconfig.yml" ]; then
    echo "Using project sgconfig.yml..."
    $AST_GREP_CMD scan --config sgconfig.yml --fix --lang rust || echo "AST-grep fixes completed with warnings"
else
    echo "No sgconfig.yml found, using default rules..."
    if [ -d ".ast-grep/rules" ]; then
        for rule_file in .ast-grep/rules/*.yml; do
            if [ -f "$rule_file" ]; then
                echo "Applying $(basename "$rule_file")..."
                $AST_GREP_CMD scan -r "$rule_file" --fix . || echo "Rule $(basename "$rule_file") completed with warnings"
            fi
        done
    else
        echo "No AST-grep rules found"
    fi
fi

# Phase 4: Cargo fixes
echo "🦀 Phase 4: Cargo automatic fixes..."

# Run cargo fix
echo "Running cargo fix..."
cargo fix --allow-dirty --allow-staged || echo "Cargo fix completed with warnings"

# Run clippy fixes
echo "Running clippy fixes..."
cargo clippy --fix --allow-dirty --allow-staged --all-targets --all-features || echo "Clippy fixes completed with warnings"

# Phase 5: Format
echo "🎨 Phase 5: Code formatting..."
cargo fmt

# Phase 6: Validation
echo "✅ Phase 6: Post-fix validation..."

echo "Checking compilation after fixes..."
if cargo check --all-targets --all-features; then
    echo "✅ Project compiles successfully after fixes"
else
    echo "❌ Fixes broke compilation, restoring backup..."
    git stash pop || echo "No backup to restore"
    exit 1
fi

# Run tests if they exist
echo "Running tests..."
if cargo test --no-run &> /dev/null; then
    cargo test || echo "⚠️ Some tests failed"
else
    echo "No tests to run"
fi

# Phase 7: Report generation
echo "📊 Phase 7: Generating fix report..."

cat > "rust-auto-fix-report.md" << EOF
# Rust Auto-Fix Report

**Generated**: $(date -u '+%Y-%m-%d %H:%M:%S UTC')
**Project**: agent-sync
**Script**: rust-auto-fix.sh

## Fixes Applied

### AST-grep Structural Fixes
- Memory safety improvements
- Performance optimizations
- Error handling enhancements
- Async pattern improvements
- Redis integration patterns
- Code style corrections

### Cargo Fixes
- Automatic compiler suggestions
- Clippy lint fixes
- Code formatting (rustfmt)

## Validation Results

\`\`\`
$(cargo check --all-targets --all-features 2>&1 || echo "Compilation check failed")
\`\`\`

## Changed Files

\`\`\`
$(git diff --name-only 2>/dev/null || echo "No changes detected")
\`\`\`

---
*Generated by Claude Framework Rust Auto-Fix*
EOF

echo "✅ Auto-fix complete! Report saved to rust-auto-fix-report.md"

# Show summary
if git diff --quiet; then
    echo "ℹ️ No changes were made"
else
    echo "📝 Changes made to the following files:"
    git diff --name-only
    echo ""
    echo "To commit these changes:"
    echo "  git add -A"
    echo "  git commit -m '🤖 Rust auto-fixes applied'"
fi

echo "🎉 Rust auto-fix process completed successfully!"